import { launchBrowser, baseURL } from './browser-support.mjs';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await launchBrowser();
const key = 'reef-demo-state-v10';
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.clock.setFixedTime(new Date('2026-09-08T04:00:00Z'));
  await page.goto(`${baseURL}/`);
  await page.waitForFunction(key => !!localStorage.getItem(key), key);
  await page.evaluate(key => {
    const saved = JSON.parse(localStorage.getItem(key));
    saved.tasks = []; saved.maintenanceCycles = []; saved.notificationEnabled = false;
    localStorage.setItem(key, JSON.stringify(saved));
  }, key);
  await page.reload(); await page.locator("main[aria-busy=false]").waitFor();
  const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
  const open = async () => {
    await page.getByRole('button', { name: '打开设置' }).click();
    await page.getByRole('button', { name: /稳定滴定配方/ }).click();
  };
  const navTasks = () => page.locator('.bottom-nav').getByRole('button', { name: '✓ 任务' }).click();
  const completed = () => page.getByRole('tab', { name: /^已完成/ }).click();
  const pending = () => page.getByRole('tab', { name: /^待处理/ }).click();
  const listCycle = page.locator('.task-list [data-testid="maintenance-cycle-task"]');
  const date = day => page.locator('.calendar-grid button:not(.outside)').filter({ has: page.locator('.calendar-day-number', { hasText: new RegExp(`^${day}$`) }) }).click();
  const submit = () => page.getByRole('button', { name: /^已配好/ }).click();
  const waitCycles = n => page.waitForFunction(({ key, n }) => JSON.parse(localStorage.getItem(key)).maintenanceCycles.length === n, { key, n });

  await open();
  await page.getByLabel('每日 PO₄ 上升（mg/L）').fill('0.05');
  await page.getByLabel('单位').selectOption('ml/min');
  await page.getByLabel('泵流速', { exact: true }).fill('100');
  assert.match(await page.getByTestId('maintenance-stock').innerText(), /5 ml/);
  await submit(); await waitCycles(1);
  assert.deepEqual((await read()).tasks, []);
  await navTasks(); await pending();
  assert.equal(await listCycle.count(), 0);
  await completed(); assert.match(await listCycle.innerText(), /5 天/);
  await date(9); assert.match(await listCycle.innerText(), /4 天/);
  await date(12); assert.equal(await listCycle.count(), 0);
  assert.match(await page.locator('.daily-agenda [data-testid="maintenance-cycle-task"]').innerText(), /添加滴定液/);

  await page.clock.setFixedTime(new Date('2026-09-10T04:00:00Z'));
  await page.reload(); await page.locator("main[aria-busy=false]").waitFor(); await navTasks(); await completed();
  const before = (await read()).maintenanceCycles;
  await listCycle.getByRole('button', { name: '提前续配' }).click();
  assert.equal(await page.getByRole('button', { name: /^已配好/ }).isDisabled(), true);
  await page.getByLabel('上次滴定液还有残留吗？').selectOption('yes');
  assert.equal(await page.getByLabel('保留残液体积（mL）').inputValue(), '300');
  assert.match(await page.getByTestId('maintenance-stock').innerText(), /2 ml/);
  await page.getByLabel('保留残液体积（mL）').fill('501');
  assert.equal(await page.getByRole('button', { name: /^已配好/ }).isDisabled(), true);
  await page.getByRole('button', { name: '关闭滴定计算器' }).click();
  assert.deepEqual((await read()).maintenanceCycles, before);
  await listCycle.getByRole('button', { name: '提前续配' }).click();
  await page.getByLabel('上次滴定液还有残留吗？').selectOption('no');
  assert.match(await page.getByTestId('maintenance-stock').innerText(), /5 ml/);
  await page.getByLabel('上次滴定液还有残留吗？').selectOption('yes');
  await mkdir('tests/artifacts', { recursive: true });
  await page.getByTestId('maintenance-stock').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'tests/artifacts/maintenance-residual.png', fullPage: true, animations: 'disabled' });
  await submit(); await waitCycles(2);
  const next = (await read()).maintenanceCycles;
  assert.equal(next[0].closedOnDate, '2026-09-10');
  assert.equal(next[1].retainedMl, 300); assert.equal(next[1].addedStockMl, 2);
  assert.notEqual(next[0].id, next[1].id);
  assert.deepEqual((await read()).tasks, []);
  await date(9); assert.match(await listCycle.innerText(), /4 天/);
  await date(12); assert.equal(await listCycle.count(), 1); assert.match(await listCycle.innerText(), /3 天/);

  await page.clock.setFixedTime(new Date('2026-09-14T04:00:00Z'));
  await page.reload(); await page.locator("main[aria-busy=false]").waitFor();
  await page.locator('.home-todos [data-testid="maintenance-cycle-task"]').waitFor();
  assert.equal(await page.locator('.home-todos [data-testid="maintenance-cycle-task"]').count(), 1);
  await navTasks(); await pending(); assert.equal(await listCycle.count(), 1);
  assert.match(await listCycle.innerText(), /待处理/);
  await page.screenshot({ path: 'tests/artifacts/maintenance-refill.png', fullPage: true, animations: 'disabled' });
  await page.clock.setFixedTime(new Date('2026-09-16T04:00:00Z'));
  await page.reload(); await page.locator("main[aria-busy=false]").waitFor(); await navTasks(); await pending(); assert.equal(await listCycle.count(), 1);
  await listCycle.getByRole('button', { name: '添加滴定液' }).click();
  await page.getByLabel('上次滴定液还有残留吗？').selectOption('no');
  await submit(); await waitCycles(3);
  assert.equal(await listCycle.count(), 0);
  await page.reload(); await page.locator("main[aria-busy=false]").waitFor(); await navTasks(); await completed(); assert.equal(await listCycle.count(), 1);
  assert.deepEqual((await read()).tasks, []);
  await open();
  await page.getByLabel('选择指标').selectOption('kh');
  assert.equal(await page.getByLabel('上次滴定液还有残留吗？').count(), 0);
  assert.equal(await page.getByLabel('每日 KH 下降（dKH）').inputValue(), '0.5');
  await page.getByLabel('单位', { exact: false }).selectOption('ml/min');
  await page.getByLabel('泵流速', { exact: true }).fill('100');
  await page.getByLabel('KH 母液浓度').selectOption('8');
  assert.match(await page.getByTestId('maintenance-stock').innerText(), /400 ml/);
  await submit(); await waitCycles(4);
  assert.equal(await listCycle.count(), 2);
  const allCycles = (await read()).maintenanceCycles;
  assert.equal(allCycles.filter(c => !c.closedOnDate && c.chemical === 'po4').length, 1);
  assert.equal(allCycles.filter(c => !c.closedOnDate && c.chemical === 'kh').length, 1);
  await listCycle.filter({ hasText: 'KH 每日平衡' }).getByRole('button', { name: '提前续配' }).click();
  await page.getByLabel('上次滴定液还有残留吗？').selectOption('yes');
  await page.getByLabel('保留残液体积（mL）').fill('300');
  await page.getByLabel('KH 母液浓度').selectOption('6');
  assert.match(await page.getByTestId('maintenance-stock').innerText(), /120 ml/);
  await page.getByRole('button', { name: '关闭滴定计算器' }).click();
  assert.deepEqual((await read()).maintenanceCycles, allCycles);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('PASS: web creation, no daily to-dos, future completed countdown, last-day refill, overdue persistence, residual preview/edit/cancel/save, old history, refresh, mobile layout and console.');
} finally { await browser.close(); }
